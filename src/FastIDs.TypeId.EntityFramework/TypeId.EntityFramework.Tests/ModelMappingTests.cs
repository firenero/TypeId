using FluentAssertions;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Metadata;

namespace FastIDs.TypeId.EntityFramework.Tests;

/// <summary>
/// Verifies the relational model built for a real-world provider (SQL Server) without connecting to a database.
/// </summary>
[TestFixture]
public class ModelMappingTests
{
    private TestDbContext _context = null!;
    private IModel _model = null!;

    [SetUp]
    public void SetUp()
    {
        var options = new DbContextOptionsBuilder<TestDbContext>()
            .UseSqlServer("Server=(none);Database=TypeIdTests;Trusted_Connection=True;")
            .Options;
        _context = new TestDbContext(options);
        _model = _context.GetService<IDesignTimeModel>().Model;
    }

    [TearDown]
    public void TearDown() => _context.Dispose();

    private IProperty Property<TEntity>(string name) =>
        _model.FindEntityType(typeof(TEntity))!.FindProperty(name)!;

    [Test]
    public void TypeId_ByConvention_IsAsciiString90()
    {
        var property = Property<User>(nameof(User.Id));

        property.GetColumnType().Should().Be("varchar(90)");
        property.GetValueConverter().Should().BeOfType<TypeIdToStringConverter>();
        property.GetValueConverter()!.ProviderClrType.Should().Be(typeof(string));
        property.GetValueComparer().Should().BeOfType<TypeIdValueComparer>();
    }

    [Test]
    public void NullableTypeId_ByConvention_IsNullableString()
    {
        var property = Property<User>(nameof(User.ReferrerId));

        property.IsNullable.Should().BeTrue();
        property.GetColumnType().Should().Be("varchar(90)");
        property.GetValueConverter().Should().BeOfType<TypeIdToStringConverter>();
    }

    [Test]
    public void TypeIdDecoded_ByConvention_IsAsciiString90()
    {
        var property = Property<Account>(nameof(Account.Id));

        property.GetColumnType().Should().Be("varchar(90)");
        property.GetValueConverter().Should().BeOfType<TypeIdDecodedToStringConverter>();
    }

    [Test]
    public void NullableTypeIdDecoded_ByConvention_IsNullableString()
    {
        var property = Property<Account>(nameof(Account.ParentId));

        property.IsNullable.Should().BeTrue();
        property.GetColumnType().Should().Be("varchar(90)");
    }

    [Test]
    public void TypeId_WithGuidConversion_IsUniqueIdentifier()
    {
        var property = Property<Order>(nameof(Order.Id));

        property.GetColumnType().Should().Be("uniqueidentifier");
        property.GetValueConverter().Should().BeOfType<TypeIdToGuidConverter>();
        property.GetValueConverter()!.ProviderClrType.Should().Be(typeof(Guid));
        property.GetValueComparer().Should().BeOfType<TypeIdValueComparer>();
    }

    [Test]
    public void TypeIdDecoded_WithGuidConversion_IsUniqueIdentifier()
    {
        var property = Property<Invoice>(nameof(Invoice.Id));

        property.GetColumnType().Should().Be("uniqueidentifier");
        property.GetValueConverter().Should().BeOfType<TypeIdDecodedToGuidConverter>();
    }

    [Test]
    public void ForeignKeyToStringKey_IsString90()
    {
        var property = Property<Order>(nameof(Order.UserId));

        property.GetColumnType().Should().Be("varchar(90)");
    }

    [Test]
    public void KeyWithGenerator_IsGeneratedOnAdd_WithoutStoreDefault()
    {
        foreach (var property in new[]
                 {
                     Property<User>(nameof(User.Id)), Property<Account>(nameof(Account.Id)),
                     Property<Order>(nameof(Order.Id)), Property<Invoice>(nameof(Invoice.Id))
                 })
        {
            property.ValueGenerated.Should().Be(ValueGenerated.OnAdd);
            // The store must never generate the value: it is generated by the client.
            property.GetDefaultValueSql().Should().BeNull();
        }
    }
}
