using Microsoft.Data.Sqlite;
using Microsoft.EntityFrameworkCore;

namespace FastIDs.TypeId.EntityFramework.Tests;

/// <summary>User stored with the default (string) mapping; <see cref="TypeId"/> key generated on the client.</summary>
public class User
{
    public TypeId Id { get; set; }
    public TypeId? ReferrerId { get; set; }
    public string Name { get; set; } = "";
    public List<Order> Orders { get; set; } = new();
}

/// <summary>Account stored with the default (string) mapping using <see cref="TypeIdDecoded"/>.</summary>
public class Account
{
    public TypeIdDecoded Id { get; set; }
    public TypeIdDecoded? ParentId { get; set; }
    public string Name { get; set; } = "";
}

/// <summary>Order stored in a UUID column using <see cref="TypeId"/>; belongs to <see cref="User"/> (string key).</summary>
public class Order
{
    public TypeId Id { get; set; }
    public TypeId UserId { get; set; }
    public User? User { get; set; }
}

/// <summary>Invoice stored in a UUID column using <see cref="TypeIdDecoded"/>.</summary>
public class Invoice
{
    public TypeIdDecoded Id { get; set; }
}

/// <summary>Entity with keys that are not generated by EF.</summary>
public class Manual
{
    public TypeId Id { get; set; }
    public TypeIdDecoded Decoded { get; set; }
}

public class TestDbContext : DbContext
{
    public TestDbContext(DbContextOptions<TestDbContext> options) : base(options)
    {
    }

    public DbSet<User> Users => Set<User>();
    public DbSet<Account> Accounts => Set<Account>();
    public DbSet<Order> Orders => Set<Order>();
    public DbSet<Invoice> Invoices => Set<Invoice>();
    public DbSet<Manual> Manuals => Set<Manual>();

    protected override void ConfigureConventions(ModelConfigurationBuilder configurationBuilder)
    {
        configurationBuilder.ConfigureForTypeId();
    }

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        modelBuilder.Entity<User>(b =>
        {
            b.Property(x => x.Id).HasTypeIdGenerator("user");
            b.HasOne<User>().WithMany().HasForeignKey(x => x.ReferrerId);
        });

        modelBuilder.Entity<Account>(b =>
        {
            b.Property(x => x.Id).HasTypeIdGenerator("acc");
            b.HasOne<Account>().WithMany().HasForeignKey(x => x.ParentId);
        });

        modelBuilder.Entity<Order>(b =>
        {
            b.Property(x => x.Id).HasTypeIdGuidConversion("order").HasTypeIdGenerator("order");
            // The foreign key is a string column because it references the string primary key of User.
            b.HasOne(x => x.User).WithMany(x => x.Orders).HasForeignKey(x => x.UserId);
        });

        modelBuilder.Entity<Invoice>(b =>
        {
            b.Property(x => x.Id).HasTypeIdGuidConversion("inv").HasTypeIdGenerator("inv");
        });

        modelBuilder.Entity<Manual>(b =>
        {
            b.Property(x => x.Id).ValueGeneratedNever();
            b.Property(x => x.Decoded).HasTypeIdGuidConversion("");
        });
    }
}

/// <summary>Creates contexts backed by an in-memory SQLite database that lives as long as the factory.</summary>
public sealed class SqliteContextFactory : IDisposable
{
    private readonly SqliteConnection _connection = new("DataSource=:memory:");

    public SqliteContextFactory()
    {
        _connection.Open();
        using var context = CreateContext();
        context.Database.EnsureCreated();
    }

    public SqliteConnection Connection => _connection;

    public TestDbContext CreateContext() =>
        new(new DbContextOptionsBuilder<TestDbContext>().UseSqlite(_connection).Options);

    public void Dispose() => _connection.Dispose();
}
